func CheckBenchedInNodes(nodesStr string, benchedJSON string) map[string][]string {
	// Parse nodes into a set for O(1) lookup
	nodeSet := make(map[string]bool)
	for _, line := range strings.Split(strings.TrimSpace(nodesStr), "\n") {
		nodeSet[strings.TrimSpace(line)] = true
	}

	// Parse benched JSON
	var benchedData struct {
		BenchedByChains map[string][]string `json:"benchedByChains"`
	}
	if err := json.Unmarshal([]byte(benchedJSON), &benchedData); err != nil {
		return nil
	}

	// Find which benched nodes appear in nodes
	result := make(map[string][]string)
	for chain, benchedNodes := range benchedData.BenchedByChains {
		var found []string
		for _, nodeID := range benchedNodes {
			if nodeSet[nodeID] {
				found = append(found, nodeID)
			}
		}
		if len(found) > 0 {
			result[chain] = found
		}
	}

	return result
}

